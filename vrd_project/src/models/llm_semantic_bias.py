"""
LLM Semantic Bias Module for Zero-Shot VRD
=============================================

Replaces the data-driven FrequencyBias with commonsense-aware semantic priors
generated offline by a Large Language Model (LLM).

Instead of P(predicate | subject, object) from training data co-occurrence,
this uses P_LLM(predicate | subject, object) from LLM reasoning.

Key advantages over FrequencyBias:
- Not biased toward training data distribution (addresses long-tail problem)
- Captures real-world commonsense (e.g., person + horse → riding, not just "on")
- Provides meaningful priors even for unseen (subject, object) pairs (zero-shot)
"""

import json
import numpy as np
import torch
import torch.nn as nn
from pathlib import Path
from typing import Dict, List, Optional, Tuple, Any


class LLMSemanticBias(nn.Module):
    """
    LLM-generated commonsense bias for predicate prediction.

    Loads a pre-computed prior matrix generated by an LLM and uses it
    as a semantic bias during inference, replacing statistical frequency bias.

    The key trainable parameter is `tau` (temperature), which controls
    how strongly the LLM priors influence predictions:
        logits_bias = log(P_LLM) / tau

    Args:
        num_obj_classes: Number of object classes
        num_pred_classes: Number of predicate classes
        alpha: Overall weight for the bias
        learnable_temperature: Whether tau is learnable
        initial_temperature: Initial value of tau
    """

    def __init__(
        self,
        num_obj_classes: int = 151,
        num_pred_classes: int = 51,
        alpha: float = 1.0,
        learnable_temperature: bool = True,
        initial_temperature: float = 1.0
    ):
        super().__init__()

        self.num_obj_classes = num_obj_classes
        self.num_pred_classes = num_pred_classes
        self.alpha = alpha

        # Prior matrix: [num_obj, num_obj, num_pred]
        # Stores P_LLM(pred | subj_class, obj_class)
        self.register_buffer(
            'prior_matrix',
            torch.zeros(num_obj_classes, num_obj_classes, num_pred_classes)
        )

        # Learnable temperature parameter
        if learnable_temperature:
            self.tau = nn.Parameter(torch.tensor(initial_temperature))
        else:
            self.register_buffer('tau', torch.tensor(initial_temperature))

        # Flag for whether priors have been loaded
        self.register_buffer('is_loaded', torch.tensor(False))

    def load_priors(
        self,
        priors_path: str,
        obj_to_idx: Optional[Dict[str, int]] = None,
        pred_to_idx: Optional[Dict[str, int]] = None,
        smoothing: float = 1e-3
    ) -> None:
        """
        Load LLM-generated priors from JSON file.

        Expected JSON format:
        {
            "priors": {
                "person": {
                    "horse": {"riding": 9, "near": 5, "on": 7, ...},
                    "table": {"at": 8, "near": 6, ...},
                    ...
                },
                ...
            },
            "obj_classes": [...],
            "pred_classes": [...]
        }

        Args:
            priors_path: Path to llm_priors.json
            obj_to_idx: Object name → index mapping
            pred_to_idx: Predicate name → index mapping
            smoothing: Smoothing constant for zero entries
        """
        priors_path = Path(priors_path)
        if not priors_path.exists():
            print(f"Warning: LLM priors file not found at {priors_path}")
            print("Using uniform priors (no commonsense bias)")
            self._set_uniform_priors()
            return

        with open(priors_path, 'r') as f:
            data = json.load(f)

        priors_data = data.get('priors', {})

        if obj_to_idx is None:
            # Build from the file's class lists
            obj_classes = data.get('obj_classes', {})
            obj_to_idx = obj_classes if isinstance(obj_classes, dict) else \
                {name: i for i, name in enumerate(obj_classes)}

        if pred_to_idx is None:
            pred_classes = data.get('pred_classes', {})
            pred_to_idx = pred_classes if isinstance(pred_classes, dict) else \
                {name: i for i, name in enumerate(pred_classes)}

        # Fill the prior matrix
        prior_matrix = torch.full(
            (self.num_obj_classes, self.num_obj_classes, self.num_pred_classes),
            smoothing
        )

        for subj_name, obj_dict in priors_data.items():
            subj_idx = obj_to_idx.get(subj_name)
            if subj_idx is None:
                continue

            for obj_name, pred_scores in obj_dict.items():
                obj_idx = obj_to_idx.get(obj_name)
                if obj_idx is None:
                    continue

                for pred_name, score in pred_scores.items():
                    pred_idx = pred_to_idx.get(pred_name)
                    if pred_idx is None:
                        continue

                    # Normalize LLM score (0-10) to probability-like value
                    prior_matrix[subj_idx, obj_idx, pred_idx] = \
                        max(float(score) / 10.0, smoothing)

        # Normalize rows to form valid distributions
        totals = prior_matrix.sum(dim=-1, keepdim=True)
        prior_matrix = prior_matrix / totals.clamp(min=1e-8)

        self.prior_matrix.copy_(prior_matrix)
        self.is_loaded.fill_(True)

        n_filled = (prior_matrix > smoothing + 1e-6).any(dim=-1).sum().item()
        print(f"Loaded LLM semantic bias: {n_filled} (subj, obj) pairs with priors")

    def load_from_tensor(self, prior_tensor: torch.Tensor) -> None:
        """
        Load priors directly from a tensor.

        Args:
            prior_tensor: [num_obj, num_obj, num_pred] prior probabilities
        """
        assert prior_tensor.shape == self.prior_matrix.shape, \
            f"Shape mismatch: expected {self.prior_matrix.shape}, got {prior_tensor.shape}"

        self.prior_matrix.copy_(prior_tensor)
        self.is_loaded.fill_(True)

    def _set_uniform_priors(self):
        """Set uniform priors as fallback."""
        uniform = 1.0 / self.num_pred_classes
        self.prior_matrix.fill_(uniform)
        self.is_loaded.fill_(True)

    def forward(
        self,
        subj_labels: torch.Tensor,
        obj_labels: torch.Tensor
    ) -> torch.Tensor:
        """
        Get LLM semantic bias logits for subject-object pairs.

        API-compatible with FrequencyBias.forward().

        Args:
            subj_labels: [N] subject class indices
            obj_labels: [N] object class indices

        Returns:
            [N, num_pred_classes] bias logits
        """
        if not self.is_loaded:
            return torch.zeros(
                len(subj_labels),
                self.num_pred_classes,
                device=subj_labels.device
            )

        # Lookup prior probabilities
        probs = self.prior_matrix[subj_labels, obj_labels]  # [N, num_pred]

        # Convert to log probabilities and apply temperature
        logits = torch.log(probs.clamp(min=1e-10)) / self.tau.clamp(min=0.1)

        return logits * self.alpha

    def get_top_predicates(
        self,
        subj_label: int,
        obj_label: int,
        top_k: int = 5
    ) -> List[Tuple[int, float]]:
        """
        Get top-K most likely predicates from LLM priors.

        Args:
            subj_label: Subject class index
            obj_label: Object class index
            top_k: Number of top predicates

        Returns:
            List of (predicate_idx, probability) tuples
        """
        probs = self.prior_matrix[subj_label, obj_label]
        top_probs, top_indices = probs.topk(top_k)
        return [(idx.item(), prob.item()) for idx, prob in zip(top_indices, top_probs)]

    def save(self, path: str) -> None:
        """Save LLM semantic bias to file."""
        path = Path(path)
        path.parent.mkdir(parents=True, exist_ok=True)
        torch.save({
            'prior_matrix': self.prior_matrix,
            'num_obj_classes': self.num_obj_classes,
            'num_pred_classes': self.num_pred_classes,
            'alpha': self.alpha,
            'tau': self.tau.data if isinstance(self.tau, nn.Parameter) else self.tau,
            'is_loaded': self.is_loaded
        }, path)
        print(f"Saved LLM semantic bias to {path}")

    def load(self, path: str) -> None:
        """Load LLM semantic bias from file."""
        data = torch.load(path, map_location='cpu')
        self.prior_matrix.copy_(data['prior_matrix'])
        self.alpha = data['alpha']
        if isinstance(self.tau, nn.Parameter):
            self.tau.data.fill_(data['tau'].item() if isinstance(data['tau'], torch.Tensor) else data['tau'])
        else:
            self.tau.fill_(data['tau'].item() if isinstance(data['tau'], torch.Tensor) else data['tau'])
        self.is_loaded.fill_(data['is_loaded'])
        print(f"Loaded LLM semantic bias from {path}")


def load_llm_semantic_bias(
    data_dir: str,
    num_obj_classes: int = 151,
    num_pred_classes: int = 51,
    alpha: float = 1.0,
    learnable_temperature: bool = True,
    priors_file: str = 'llm_priors.json'
) -> LLMSemanticBias:
    """
    Load and initialize LLM semantic bias from data directory.

    Args:
        data_dir: Path to processed data directory
        num_obj_classes: Number of object classes
        num_pred_classes: Number of predicate classes
        alpha: Bias weight
        learnable_temperature: Whether temperature is learnable
        priors_file: Name of LLM priors file

    Returns:
        Initialized LLMSemanticBias module
    """
    data_dir = Path(data_dir)

    # Check for pre-saved tensor
    bias_path = data_dir / 'llm_semantic_bias.pt'
    if bias_path.exists():
        bias = LLMSemanticBias(
            num_obj_classes, num_pred_classes, alpha,
            learnable_temperature=learnable_temperature
        )
        bias.load(str(bias_path))
        return bias

    # Load from JSON priors
    priors_path = data_dir / priors_file
    obj_to_idx_path = data_dir / 'obj_classes.json'
    pred_to_idx_path = data_dir / 'pred_classes.json'

    bias = LLMSemanticBias(
        num_obj_classes, num_pred_classes, alpha,
        learnable_temperature=learnable_temperature
    )

    # Load class mappings if available
    obj_to_idx = None
    pred_to_idx = None

    if obj_to_idx_path.exists():
        with open(obj_to_idx_path, 'r') as f:
            obj_to_idx = json.load(f)

    if pred_to_idx_path.exists():
        with open(pred_to_idx_path, 'r') as f:
            pred_to_idx = json.load(f)

    bias.load_priors(str(priors_path), obj_to_idx, pred_to_idx)

    # Save for future use
    if priors_path.exists():
        bias.save(str(bias_path))

    return bias
