/** Embed image with caption. maxW in px (96dpi screen pixels). */
function fig(key, caption, maxW = 560) {
  const data = IMG[key];
  const [ow, oh] = DIM[key];
  const scale = Math.min(maxW / ow, 480 / oh, 1.0);
  const w = Math.round(ow * scale);
  const h = Math.round(oh * scale);

  const imgEl = data
    ? new ImageRun({ type: "png", data, transformation: { width: w, height: h } })
    : new TextRun({ text: `[Figure not found — ${caption}]`, font: F, size: S12, italics: true });

  return [
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: spTight, children: [imgEl] }),
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: spFig,
      children: [new TextRun({ text: caption, font: F, size: S12, italics: true })]
    })
  ];
}

