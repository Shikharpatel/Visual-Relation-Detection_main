/** No-border two-column signature table */
function sigRow(l1, l2, r1, r2) {
  const nb = { style: BorderStyle.NONE, size: 0, color: "FFFFFF" };
  const cell = (a, b) => new TableCell({
    borders: { top: nb, bottom: nb, left: nb, right: nb },
    width: { size: Math.floor(CW / 2), type: WidthType.DXA },
    children: [
      new Paragraph({ spacing: spTight, children: [new TextRun({ text: a, font: F, size: S12, bold: true })] }),
      new Paragraph({ spacing: spTight, children: [new TextRun({ text: b, font: F, size: S12 })] })
    ]
  });
  return new Table({
    width: { size: CW, type: WidthType.DXA },
    columnWidths: [Math.floor(CW / 2), Math.floor(CW / 2)],
    borders: { top: nb, bottom: nb, left: nb, right: nb, insideH: nb, insideV: nb },
    rows: [new TableRow({ children: [cell(l1, l2), cell(r1, r2)] })]
  });
}

/** Bordered data table */
function tbl(headers, rows) {
  const bd = { style: BorderStyle.SINGLE, size: 4, color: "000000" };
  const borders = { top: bd, bottom: bd, left: bd, right: bd };
  const colW = Math.floor(CW / headers.length);
  const mkCell = (text, isHdr) => new TableCell({
    borders, width: { size: colW, type: WidthType.DXA },
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    shading: { fill: isHdr ? "D9D9D9" : "FFFFFF", type: ShadingType.CLEAR },
    children: [new Paragraph({
      spacing: spTight,
      children: [new TextRun({ text, font: F, size: S12, bold: isHdr })]
    })]
  });
  return new Table({
    width: { size: CW, type: WidthType.DXA },
    columnWidths: Array(headers.length).fill(colW),
    rows: [
      new TableRow({ tableHeader: true, children: headers.map(h => mkCell(h, true)) }),
      ...rows.map(r => new TableRow({ children: r.map(c => mkCell(c, false)) }))
    ]
  });
}

